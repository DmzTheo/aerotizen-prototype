// Writes launcher/src/backgrounds/proposalScenes.ts from ../backgrounds (gradients.js and stage.js), so the
// proposal wallpapers have one source of truth. Run: node tools/proposal-scenes.mjs
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";
import * as prettier from "prettier";

const root = fileURLToPath(new URL("../", import.meta.url));
const backgrounds = path.join(root, "..", "backgrounds");
const target = path.join(root, "launcher/src/backgrounds/proposalScenes.ts");

const evaluate = async (file) => {
  const window = {};
  vm.runInNewContext(await readFile(path.join(backgrounds, file), "utf8"), { window }, { filename: file });
  return window;
};
const { AEROTIZEN_GRADIENTS: gradients } = await evaluate("gradients.js");
const { StageBackground: stage } = await evaluate("stage.js");

// Display order in Settings, the order of the Themes section that uses them (Stage, animated, sits with the animated
// wallpapers); Pastel is light, so the launcher's floating text turns dark on it.
const STATIC = ["prism", "pastel", "coral", "twilightpeaks", "borealis"];
const LIGHT = new Set(["pastel"]);
for (const id of STATIC) {
  if (typeof gradients[id] !== "string") throw new Error("Missing gradient: " + id);
}
if (typeof stage.fallback !== "string") throw new Error("Missing Stage fallback");
if (typeof stage.swatch !== "string") throw new Error("Missing Stage swatch");

const literal = (value) => JSON.stringify(value);
const lines = [
  "// Generated by tools/proposal-scenes.mjs from ../backgrounds (gradients.js, stage.js). Do not edit by hand.",
  'import type { BackgroundScene } from "../contracts/backgrounds";',
  "",
  "// The theme proposal's wallpapers: five pure CSS gradients and Stage (WebGL, backgrounds/stage.js).",
  "export const PROPOSAL_STATIC_SCENES: readonly BackgroundScene[] = [",
  ...STATIC.map(
    (id) =>
      `  { id: ${literal(id)}, proposal: true,${LIGHT.has(id) ? " light: true," : ""} base: ${literal(gradients[id])} },`,
  ),
  "];",
  "",
  "export const PROPOSAL_ANIMATED_SCENES: readonly BackgroundScene[] = [",
  `  { id: "stage", proposal: true, anim: "stage", base: ${literal(stage.fallback)} },`,
  "];",
  "",
  "// Stage's Settings swatch: a still frame of its halftone, sparkles and bokeh, laid over its fallback.",
  `export const STAGE_SWATCH = ${literal(stage.swatch)};`,
  "",
];
// Formatted like the rest of the launcher, so format:check passes on the generated file.
const options = { ...(await prettier.resolveConfig(target)), filepath: target };
await writeFile(target, await prettier.format(lines.join("\n"), options));
console.log("Wrote " + path.relative(root, target) + " (" + (STATIC.length + 1) + " scenes)");
